const assert=require('assert');
const network=require('./gcp-network');
const flight=require('./optimizer');
const model=require('./app-model');
(async()=>{
  const points=[];
  for(let y=0;y<=100;y+=10)for(let x=0;x<=100;x+=10)points.push([x,y,x/10]);
  const values=points.map(p=>1+Math.hypot(p[0]-50,p[1]-50)/100);
  const options={allowed:p=>!(p[0]<20&&p[1]<20),demands:points};
  const result=network.optimize(points,values,5,16,options);
  assert.equal(result.points.length,5);
  assert.equal(result.regionCount,4);assert(result.hasCenter);
  assert.deepEqual(result.indices,network.optimize(points,values,5,16,options).indices);
  for(const p of result.points)assert(options.allowed(p));
  for(let i=0;i<5;i++)for(let j=i+1;j<5;j++)assert(Math.hypot(result.points[i][0]-result.points[j][0],result.points[i][1]-result.points[j][1])>=16);
  if(result.greedyScore!==null)assert(result.score<=result.greedyScore+1e-9);
  const greedy=[];
  for(const i of values.map((v,i)=>i).sort((a,b)=>values[a]-values[b]))if(greedy.length<5&&greedy.every(j=>Math.hypot(points[i][0]-points[j][0],points[i][1]-points[j][1])>=16))greedy.push(i);
  const greedyRadius=Math.max(...points.map(p=>Math.min(...greedy.map(i=>Math.hypot(p[0]-points[i][0],p[1]-points[i][1])))));
  assert(result.maxDistance<greedyRadius);
  assert.equal(network.optimize(points,values,5,200).points.length,0);
  assert.equal(network.optimize(points,values,5,16,{allowed:()=>false}).points.length,0);
  const s={width:100,height:100,altitude:25,sensorWidth:13.2,focalLength:8.8,cameraProfile:'mini48',cameraOrientation:'shortAlong',fOverlap:80,sOverlap:80};
  const footprint=flight.footprint(25,s);
  assert(Math.abs(footprint.gsd-25*1.393312/8064)<1e-8);assert.equal(footprint.interval,5);
  assert.equal(flight.footprint(25,{...s,cameraProfile:'mini12'}).interval,2);
  const cams=[[-5,0,25],[5,0,25],[0,5,25],[1000,1000,25]];
  const analysis=model.analyze([[0,0,0],[500,500,0]],cams,s,'north-south');
  assert.equal(analysis.counts[0],3);assert(Number.isFinite(analysis.values[0]));
  assert.equal(analysis.counts[1],0);assert.equal(analysis.values[1],Infinity);
  const limits={minAltitude:20,maxAltitude:30,minClearance:15,minForward:80,maxForward:80,minSide:80,maxSide:80,maxGdop:10,maxPhotos:3000,acquisition:true,maxGsd:.005,minSpeed:.3,maxSpeed:5,exposure:.001,blurPixels:.5,priority:'time',compareOrientations:true};
  const plan=(await flight.solve(s,limits,{ground:0,highest:0,lowest:0},()=>({}))).plan;
  assert(plan);assert(plan.route.gsd<=limits.maxGsd);
  assert(plan.route.speed*plan.route.interval<=plan.route.photoSpacing+1e-9);
  assert(plan.route.blurPixels<=limits.blurPixels+1e-9);
  assert.equal((await flight.solve(s,{...limits,minSpeed:4},{ground:0,highest:0,lowest:0},()=>({}))).plan,null);
  await assert.rejects(flight.solve(s,{...limits,exposure:NaN},{ground:0,highest:0},()=>({})));
  console.log(`Network checks passed: coverage radius ${greedyRadius.toFixed(1)} m greedy -> ${result.maxDistance.toFixed(1)} m exchange.`);
})().catch(e=>{console.error(e);process.exit(1)});
