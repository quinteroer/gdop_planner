const assert=require('assert');
const C=require('./capture-planning.js'),F=require('./optimizer.js'),M=require('./app-model.js');
const s={width:100,height:80,altitude:30,cameraProfile:'mini48',cameraOrientation:'shortAlong',sensorWidth:13.2,focalLength:8.8,fOverlap:80,sOverlap:80};
const poly=C.polygon('[[0,0],[100,0],[100,30],[30,30],[30,80],[0,80]]',100,80);
assert(C.inside([20,70],poly));assert(!C.inside([70,70],poly));assert(C.inside([30,50],poly));
assert.throws(()=>C.polygon('[[0,0],[100,80],[100,0],[0,80]]',100,80));
assert.throws(()=>C.polygon('[[0,0],[0,0],[10,10]]',100,80));
assert.throws(()=>C.polygon('[[0,0],[101,0],[10,10]]',100,80));
for(const heading of [0,15,45,90,165]) {
  const r=F.route({...s,boundary:poly},heading,0,0);
  assert(r&&r.photos>3);assert(r.photoSpacing>0.01);
  assert(r.positions.every(p=>C.inside(p,poly)));
  assert.equal(F.trajectory(s,r,0).length,r.photos);
  assert(Math.abs(r.distance-r.positions.slice(1).reduce((v,p,i)=>v+Math.hypot(p[0]-r.positions[i][0],p[1]-r.positions[i][1]),0))<1e-8);
}
assert.equal(F.route({...s,boundary:poly},45,0,0,'curved'),null);
assert(C.sight([0,0,0],[10,0,10],()=>0,1));
assert(!C.sight([0,0,0],[10,0,10],x=>x>4&&x<6?20:0,1));
assert(!C.sight([0,0,0],[10,0,10],()=>null,1));
const p=[50,40,0],c=[50,40,30];c.pose={heading:0,tilt:0};
assert(C.visible(p,c,s,0));assert(!C.visible([50,40,40],c,s,0));
const oblique=[50,20,30];oblique.pose={heading:0,tilt:30};
assert(C.visible(p,oblique,s,0));
assert(!C.visible([50,-60,0],oblique,s,0));
assert(!F.viewing([80,40,0],[50,40,30],s,0));
const csv='x_m,y_m,z_m,timestamp_s,heading_deg,tilt_deg,exposure_s,gsd_m,sharpness\n50,40,30,0,0,0,0.001,0.005,100\n55,40,30,1,0,0,0.01,0.005,1';
const records=C.parseCsv(csv),audit=C.audit(records,[c],10,.5,s);
assert.equal(audit.lowSharpness,1);assert.equal(audit.blurred,1);assert.equal(audit.usable.length,1);assert.equal(audit.unknownBlur,1);
assert.throws(()=>C.parseCsv(csv.replace('55,40,30,1','55,40,30,0')));
assert.throws(()=>C.parseCsv(csv.replace('0.001,0.005','-1,0.005')));
assert.throws(()=>C.parseCsv(csv.replace('50,40,30,0','50,40,,0')));
const unknown=C.audit(C.parseCsv('x_m,y_m,z_m,timestamp_s,heading_deg,tilt_deg\n50,40,30,0,0,0'),[],0,.5,s);
assert.equal(unknown.unknownSharpness,1);assert.equal(unknown.unknownBlur,1);
const a=M.analyze([p],[c],s,0);
assert.equal(a.counts[0],1);assert(a.gsds[0]>0);
assert.equal(M.analyze([p],[c],s,0,{maxGsd:.00001}).counts[0],0);
const out=C.supplement([p],[c],s,0,a,{minViews:3,minAngle:10,maxGsd:.02,minClearance:10,budget:4,terrain:()=>0},M);
assert(out.cameras.length>0);assert(out.analysis.counts[0]>a.counts[0]);assert(out.weakAfter<out.weakBefore);
console.log('Capture planning: polygon, headings, occlusion, pose, quality imports and supplemental coverage passed.');
const feedback=C.reconstruction('x_m,y_m,z_m,registered_views,reprojection_error_px\n50,40,0,5,0.5\n60,40,0,8,10',[[50,40,0],[60,40,0],[50,40,10]],2,2,3);
assert.deepEqual(feedback.supported,[true,false,false]);
assert.throws(()=>C.reconstruction('x_m,y_m,z_m,registered_views,reprojection_error_px\n0,0,0,,1',[p],2,2,3));
const target=C.supplement([p],[c],s,0,a,{minViews:1,minAngle:0,maxGsd:.02,minClearance:10,budget:2,terrain:()=>0,targetIds:[0]},M);
assert.equal(target.feedbackTargets,1);assert(target.cameras.length>0);
console.log('Reconstruction feedback: 3D neighborhood, registered-view and residual gates passed.');
(async()=>{
  const limits={minAltitude:30,maxAltitude:30,minClearance:15,minForward:80,maxForward:80,minSide:80,maxSide:80,maxGdop:10,maxPhotos:2000,acquisition:true,maxGsd:.02,maxSpeed:5,minSpeed:.01,exposure:.0001,blurPixels:.5,searchHeadings:true,priority:'time'};
  let checked=0;
  const result=await F.solve({...s,boundary:poly},limits,{ground:0,highest:0},(state,cams,score,r)=>{
    checked++;
    for(let i=1;i<cams.length;i++)assert(Math.hypot(cams[i][0]-cams[i-1][0],cams[i][1]-cams[i-1][1])/r.speed+1e-7>=r.interval);
    return null;
  });
  assert(checked>2);assert.equal(checked,result.total);assert.equal(result.plan,null);
  const cardinal=await F.solve(s,{...limits,searchHeadings:false},{ground:0,highest:0},()=>({}));
  const expanded=await F.solve(s,limits,{ground:0,highest:0},()=>({}));
  assert(expanded.plan.route.time<=cardinal.plan.route.time+1e-9);
  console.log('Rotated/clipped route timing checked across all consecutive captures and headings.');
})().catch(e=>{console.error(e);process.exitCode=1;});
