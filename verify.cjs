const { chromium } = require('C:/Users/equin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path = require('path');
const {pathToFileURL} = require('url');
const assert = require('assert');
(async () => {
  const browser = await chromium.launch({headless:true, downloadsPath:__dirname, executablePath:'C:/Users/equin/AppData/Local/ms-playwright/chromium_headless_shell-1208/chrome-headless-shell-win64/chrome-headless-shell.exe'});
  const page = await browser.newPage({viewport:{width:1400,height:1000}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
  for (const id of ['spring-run','williams-island','z-dam']) {
    await page.selectOption('#surveySelect',id);
    // Z Dam's relief cannot satisfy the strict default GSD and clearance together.
    await page.fill('#maxGsd',id==='z-dam'?'1':'0.5');
    await page.waitForFunction(() => document.querySelector('#surveyInfo').textContent.includes('GCPs selected'));
    assert.equal(await page.locator('.stat-card').count(),4);
    assert(!/NaN|Infinity/.test(await page.locator('#statsGrid').innerText()));
    await page.click('#optimizeMission');
    await page.waitForFunction(() => !document.querySelector('#optimizeMission').disabled);
    const status = await page.locator('#optimizationStatus').innerText();
    assert(status.startsWith('Applied:'), status);
    const alt = Number(await page.locator('#altitude').inputValue());
    assert(alt >= 20 && alt <= 120);
    assert(status.includes('5 GCPs'));
    assert.equal(await page.locator('#exportFlight').isDisabled(),false);
    console.log('optimized',id,status);
    await page.evaluate(() => {
      window.exportedCsv = null;
      URL.createObjectURL = blob => { blob.text().then(t => window.exportedCsv = t); return 'blob:test'; };
      HTMLAnchorElement.prototype.click = function () {};
    });
    await page.click('#exportGcps');
    await page.waitForFunction(() => window.exportedCsv !== null);
    const csv = await page.evaluate(() => window.exportedCsv);
    assert(csv.includes('EPSG:32618,EGM96'));
    const rows = csv.split('\n').slice(1).map(r=>r.split(','));
    assert(rows.length > 0);
    for (const r of rows) assert(r.slice(1,5).every(v=>Number.isFinite(Number(v))));
    assert.equal(rows.length,5);
    const minSpacing = Number(await page.locator('#minSpacing').inputValue());
    for (let i=0;i<rows.length;i++) for (let j=i+1;j<rows.length;j++) {
      assert(Math.hypot(Number(rows[i][1])-Number(rows[j][1]),Number(rows[i][2])-Number(rows[j][2])) >= minSpacing-0.002);
    }
    await page.click('#exportFlight');
    await page.waitForFunction(() => window.exportedCsv.startsWith('waypoint_id'));
    const flight = (await page.evaluate(() => window.exportedCsv)).split('\n').slice(1);
    assert(flight.length >= 3 && flight.length <= 3000);
    assert(flight.every(row => row.includes('EPSG:32618,EGM96,')));
    assert(flight.every(row => Number(row.split(',').at(-2)) > 0 && Number(row.split(',').at(-1)) === 5));
    const highest = await page.evaluate(id => Math.max(...window.SURVEY_SITES.find(s=>s.id===id).elevations.filter(z=>z!==null)),id);
    assert(Number(flight[0].split(',')[4])-highest >= Number(await page.locator('#minClearance').inputValue())-0.001);
    // Display changes must preserve the optimized route and export.
    await page.locator('label.switch').filter({has:page.locator('#toggleFlight')}).click();
    assert.equal(await page.locator('#exportFlight').isDisabled(),false);
    await page.locator('label.switch').filter({has:page.locator('#toggleFlight')}).click();
    console.log(id,await page.locator('#surveyInfo').innerText());
  }
  await page.screenshot({path:path.join(__dirname,'preview.png')});
  await page.selectOption('#pathMode','curved');
  await page.click('#optimizeMission');
  await page.waitForFunction(() => !document.querySelector('#optimizeMission').disabled);
  assert((await page.locator('#optimizationStatus').innerText()).includes('Curved turns: 2 m radius'));
  await page.click('#exportFlight');
  await page.waitForFunction(() => window.exportedCsv.includes(',false,'));
  const curvedCsv = await page.evaluate(() => window.exportedCsv);
  assert(curvedCsv.includes(',true,'));
  await page.locator('#controls').evaluate(e=>e.scrollTop=0);
  await page.screenshot({path:path.join(__dirname,'preview-curved.png')});
  await page.fill('#turnBuffer','1');
  await page.click('#optimizeMission');
  await page.waitForFunction(() => !document.querySelector('#optimizeMission').disabled);
  assert((await page.locator('#optimizationStatus').innerText()).includes('No accepted plan'));
  assert.equal(await page.locator('#exportFlight').isDisabled(),false);
  await page.fill('#turnBuffer','20');
  const oldAltitude = await page.locator('#altitude').inputValue();
  await page.fill('#minAltitude','120');
  await page.fill('#maxAltitude','20');
  await page.click('#optimizeMission');
  await page.waitForFunction(() => !document.querySelector('#optimizeMission').disabled);
  assert((await page.locator('#optimizationStatus').innerText()).includes('Check limit ranges'));
  assert.equal(await page.locator('#altitude').inputValue(),oldAltitude);
  await page.fill('#minAltitude','20');
  await page.fill('#maxAltitude','20');
  await page.fill('#minClearance','100');
  await page.click('#optimizeMission');
  await page.waitForFunction(() => !document.querySelector('#optimizeMission').disabled);
  assert((await page.locator('#optimizationStatus').innerText()).includes('No accepted plan'));
  assert.equal(await page.locator('#altitude').inputValue(),oldAltitude);
  await page.check('#excludeMode');
  const box=await page.locator('canvas').boundingBox();
  const click={x:box.x+box.width/2,y:box.y+box.height/2};
  await page.mouse.click(click.x,click.y);
  assert.equal(await page.locator('#exportFlight').isDisabled(),true);
  assert(!/NaN|Infinity/.test(await page.locator('#statsGrid').innerText()));
  await page.click('#clearExclusions');
  await page.selectOption('#surveySelect','');
  assert.equal(await page.locator('#exportFlight').isDisabled(),true);
  assert(!/NaN|Infinity/.test(await page.locator('#statsGrid').innerText()));
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('All browser checks passed.');
})().catch(e=>{console.error(e);process.exit(1)});
